double **Memory_allocation_for_2D(int rows, int cols)
{
	double **pin2D;
	int i;
	pin2D = (double **) malloc(rows *sizeof(double *));
	if (pin2D == NULL)
	{
		printf("Error: Not enough memory");
		exit(1);
	}
	for (i=0; i<rows;i++)
	{
		pin2D[i] = (double *)malloc(cols * sizeof(double));
		if (pin2D[i] == NULL)
		{
			printf("Error: Not enough memory");
			exit(1);
		} 
	}
	return pin2D;
}

