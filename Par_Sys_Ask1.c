// Συνάρτηση αυτόματης αρχικοποίησης (Διαγώνιος = 1, Εκτός διαγωνίου = 0)
void initialize_matrix_automatic(int N, double **A) {
    int i, j;
    #pragma omp parallel for collapse(2) shared(A, N) private(i, j) schedule(static)
    for (i = 0; i < N; i++) {
        for (j = 0; j < N; j++) {
            if (i == j) {
                A[i][j] = 1.0;
            } else {
                A[i][j] = 0.0;
            }
        }
    }
}

// Ερώτημα (a): Έλεγχος αν ο πίνακας είναι αυστηρά διαγώνια δεσπόζων
int check_diagonally_dominant(int N, double **A)
{
	int flag = 1;
    int i, j;
    double sum;
	
	/*Δημιουργία της ομάδας νημάτων που παραλληλοποιεί/διαμοιράζει αυτόματα τις επαναλήψεις του εξωτερικού βρόχου for (τις γραμμές του πίνακα).
	Το shared() δηλώνει ότι ο πίνακας Α, η διαστάσεις NxN και το flag είναι κοινόχρηστες μεταβλητές στη μνήμη για όλα τα νήματα.
	Το private() δημιουργεί ένα ιδιωτικό αντίγραφο των μετρητών i, j και του αθροίσματος sum για κάθε νήμα, ώστε να υπολογίζονται αυτόνομα χωρίς επικαλύψεις.
	Το schedule(static) αναθέτει τις γραμμές του πίνακα στα νήματα με προκαθορισμένη, ισομερή σειρά εξ αρχής.*/
	#pragma omp parallel for shared(A, N, flag) private(i, j, sum) schedule(static) 
	for (i=0;i<N;i++)
	{
		if (flag==1) // Διακόπτουμε τους περιττούς υπολογισμούς αν κάποιο άλλο νήμα βρήκε ήδη σφάλμα
		{
			sum = 0.0;//Αρχικοποιούμε το sum, για κάθε γραμμή ξεχωριστά 
			for (j = 0; j < N; j++) 
			{
				if (i != j) 
				{
                    sum += fabs(A[i][j]); // Προσθήκη των απολύτων τιμών εκτός διαγωνίου (Σ|Αij| όπου j=0…N-1 i<>j)
                }
            }
			//Έλεγχος αν είναι «αυστηρά διαγώνια δεσπόζων» 
			if (sum >= fabs(A[i][i])) //Άμα ΔΕΝ ισχύει: |Aii| > Σ|Aij| όπου j=0…N-1 i<>j
			{
				/*Ασφαλής εγγραφή στη shared μεταβλητή flag. 
				Το atomic διασφαλίζει την ατομικότητα κατά την εγγραφή της τιμής στην κοινή μεταβλητή flag (εκτέλεση ως μία αδιαίρετη πράξη). 
				Αποτρέπει συνθήκες ανταγωνισμού (race conditions) αν περισσότερα από ένα νήματα βρουν ταυτόχρονα σφάλμα στη διαγώνιο.
				Χρησιμοποιειται write για να εκχωρήσουμε/γράψουμε μια νέα τιμή στη μεταβλητή (flag = 0;), αγνοώντας την προηγούμενη τιμή της.*/
				#pragma omp atomic write 
                flag = 0;
            }
		}
	}
	return flag;
}

// Ερώτημα (b): Υπολογισμός μέγιστου κατ' απόλυτη τιμή στοιχείου της διαγωνίου m = max(|Aii|)
double get_max_diagonal(int N, double **A)
{
	double m = 0.0;
	int i; 
	/*Παραλληλοποίηση στις επαναλήψεις του βρόχου της διαγωνίου (i=0 ... N-1). 
	Το reduction(max:m) αρχικοποιεί ένα τοπικό αντίγραφο της μεταβλητής m για κάθε νήμα, υπολογίζει παράλληλα το μέγιστο σε κάθε νήμα και στο τέλος συγκρίνει τα τοπικά μέγιστα για να ενημερώσει το τελικό m χωρις race conditions.
	Το private(i) ορίζει το i ως ιδιωτικό μετρητή για κάθε νήμα. 
	Το schedule(static) αναθέτει τις γραμμές του πίνακα στα νήματα με προκαθορισμένη, ισομερή σειρά εξ αρχής.*/
	#pragma omp parallel for reduction(max:m) private(i) schedule(static)
	for (i=0;i < N; i++)
	{
		double abs_diag = fabs(A[i][i]);
		if (abs_diag > m){ m = abs_diag; }
	}
	return m;
}

// Ερώτημα (c): Κατασκευή του πίνακα B(NxN) παράλληλα
double **create_matrix_B(int N, double **A, double m) 
{
	double **B = Memory_allocation_for_2D(N,N);
	int i,j;
	/* Χρησιμοποιειται το collapse(2) για συγχώνευση των 2 επιπέδων των βρόχων (i και j) σε ένα ενιαίο πεδίο N^2 επαναλήψεων. Αντί να παραλληλοποιούνται μόνο οι N γραμμές, παραλληλοποιούνται όλα τα ΝxN στοιχεία του πίνακα B, προσφέροντας βέλτιστο διαμοιρασμό εργασίας (load balancing) μεταξύ των νημάτων.
	Το private(i, j) οριζει τα i και j ως ιδιωτικούς δείκτες βρόχων για κάθε νήμα.
	Το schedule(static) αναθέτει τις γραμμές και τις στήλες του πίνακα στα νήματα με προκαθορισμένη, ισομερή σειρά εξ αρχής.*/
	#pragma omp parallel for collapse(2) shared(A, B, N, m) private(i, j) schedule(static)
	for (i=0;i<N;i++)
	{
		for (j=0;j<N;j++)
		{
			if (i==j)
			{
				B[i][j] = m; //Για τη διαγώνιο (i == j): Bij = m
			}
			else 
			{
				B[i][j] = m - fabs(A[i][j]);// Εκτός διαγωνίου (i != j): Bij = m - |Aij|
			}
		}
	}
	return B; 
}

//Ερώτημα (d1): Εύρεση ελάχιστου στοιχείου του πίνακα B με χρήση reduction clause
double get_min_B_reduction(int N, double **B) 
{
	double min_B = B[0][0];// Αρχικοποίηση με την πρώτη τιμή του πίνακα
    int i, j;
	/* Μέσω του collapse(2) ενοποιούνται οι 2 εμφωλιασμένοι βρόχοι σε N^2 επαναλήψεις για ισομερή κατανομή στα νήματα.
	Το reduction(min: min_B) δημιουργεί τοπικό min_B για κάθε νήμα, ώστε να βρήσκουν το ελάχιστο στο δικό τους τμήμα του πίνακα B, και στο φράγμα συγχρονισμού το OpenMP να συγκρίνει τα τοπικά ελάχιστα για να ενημερώσει την τελική μεταβλητή min_B χωρίς συνθήκες ανταγωνισμού.
	Το private(i, j) οριζει τα i και j ως ιδιωτικούς δείκτες βρόχων για κάθε νήμα.
	Το schedule(static) αναθέτει τις γραμμές και τις στήλες του πίνακα στα νήματα με προκαθορισμένη, ισομερή σειρά εξ αρχής.*/
	#pragma omp parallel for collapse(2) reduction(min : min_B) private(i, j) schedule(static)
	for (i=0;i<N;i++)
	{
		for (j=0;j<N;j++)
		{
			if (B[i][j]<min_B){min_B = B[i][j];}
		}
	}
	return min_B;
}

// Ερώτημα (d2.1): Εύρεση ελάχιστου στοιχείου του B ΧΩΡΙΣ reduction, με χρήση critical
double get_min_B_critical(int N, double **B)
{
	/*Αντί κάθε νήμα να προσπαθεί να ενημερώσει το σφαιρικό ελάχιστο σε κάθε επανάληψη, υπολογίζει πρώτα το τοπικό του ελάχιστο (loc_min) και στο τέλος μπαίνει μία μόνο φορά στην κρίσιμη περιοχή (#pragma omp critical) για να ενημερώσει το σφαιρικό ελάχιστο (min_B).*/
	double min_B = B[0][0];// Σφαιρικό ελάχιστο
    int i, j;
	/*Εκκίνηση της παράλληλης περιοχής και ορισμός των κοινών (B, N, min_B) και ιδιοτηκών (i, j) μεταβλητών των νημάτων*/
	#pragma omp parallel shared(B, N, min_B) private(i, j)
	{
		double loc_min = B[0][0];// Τοπικό ελάχιστο για κάθε νήμα
		/*Παράλληλος ισομερής διαμοιρασμός των N*N επαναλήψεων (2 for loops i και j) στα νήματα*/
		#pragma omp for collapse(2) schedule(static)
		for (i=0;i<N;i++)
		{
			for (j=0;j<N;j++)
			{
				if (B[i][j]<loc_min) 
				{
					loc_min = B[i][j]; // Υπολογισμός τοπικού ελαχίστου
				}
			}
		}
		/*Εξασφάλιση ότι ένα μόνο νήμα κάθε φορά θα συγκρίνει το τοπικό του loc_min με το σφαιρικό min_B και θα το ενημερώσει με ασφάλεια.
		Εκτελείται μία φορά από κάθε νήμα μετά την ολοκλήρωση του loop.*/
		#pragma omp critical
		{
			if (loc_min<min_B) min_B = loc_min;
		} 
	}
	return min_B; 
}

// Ερώτημα (d2.2): Εύρεση ελάχιστου στοιχείου του B με αλγόριθμο Δυαδικού Δέντρου (Tree Reduction)
double get_min_B_tree(int N, double **B)
{
	/*Για την υλοποίηση του αλγόριθμου Δυαδικού Δέντρου (Binary Tree Reduction) πάνω στον πίνακα B(NxN), η πιο καθαρή προσέγγιση είναι να μετατρέψουμε (επιπεδοποιήσουμε - flatten) τον δισδιάστατο πίνακα σε έναν μονοδιάστατο πίνακα arr μεγέθους total = NxN.*/
	/*Στη συνέχεια, διπλασιάζουμε το βήμα (step *= 2) σε κάθε επίπεδο του δέντρου (1, 2, 4, 8, ...), συγκρίνοντας τα στοιχεία ανά ζεύγη (arr[i] με arr[i + step]), ενώ χρησιμοποιούμε τη διαταγή #pragma omp barrier για να διασφαλίσουμε ότι όλα τα νήματα έχουν ολοκληρώσει το τρέχον επίπεδο πριν προχωρήσουν στο επόμενο.*/
	int total = N*N;
	double *arr = Memory_allocation_for_1D(total);//Δυναμική δέσμευση μνήμης μονοδιάστατου πίνακα
	int i,j;
	// 1. Επιπεδοποίηση του πίνακα B(NxN) σε μονοδιάστατο πίνακα arr[N*N]
    for (i = 0; i < N; i++) {
        for (j = 0; j < N; j++) {
            arr[i * N + j] = B[i][j];
        }
    }
	int step=1;
	/*Εκκίνηση μίας παράλληλης περιοχής που διατηρείται καθ' όλη τη διάρκεια του δέντρου, καθώς και ορισμός των κοινών (arr, total, step) και ιδιοτηκών (i) μεταβλητών των νημάτων*/
	#pragma omp parallel shared(arr, total, step) private(i)
	{
		while (step<total)
		{
			/*Παράλληλος διαμοιρασμός των υπολογισμών του τρέχοντος επιπέδου του δέντρου και ανάθεση των γραμμών του πίνακα στα νήματα με προκαθορισμένη, ισομερή σειρά εξ αρχής schedule(static).*/
			#pragma omp for schedule(static)
			for (i=0;i<total-step; i+=step*2)
			{
				if (arr[i + step] < arr[i])
				{
					arr[i] = arr[i + step]; //Αποθήκευση του ελαχίστου στη ρίζα του υποδέντρου
				}
			}
			/*Διασφάλιση ότι μόνο ένα νήμα της ομάδας θα αναλάβει να διπλασιάσει το step (step *= 2;) για το επόμενο επίπεδο του δέντρου, αποφεύγοντας πολλαπλούς διπλασιασμούς από όλα τα νήματα ταυτόχρονα.*/
			#pragma omp single
			{
				step *= 2;
			}
			/*Δημιουργία ενώς ρητού σημείου συγχρονισμού (φράγμα). Κανένα νήμα δεν προχωρά στην επόμενη επανάληψη του while αν δεν φτάσουν όλα τα νήματα σε αυτό το σημείο, δηλαδή μέχρι να ενημερωθεί το step, εγγυώμενος την ορθότητα των δεδομένων μεταξύ των επιπέδων του δυαδικού δέντρου.*/
			#pragma omp barrier
		}
	}
	double min_B = arr[0];//Το τελικό ελάχιστο βρίσκεται στη ρίζα του δέντρου (θέση 0)
	Free_memory_for_1D(arr);
	return min_B;
}

